public struct FileReference: Codable, Sendable {
    public var name: String
    public var bookmark: Data?
    public var snapshotType: String?
    public var status: String
    public init(name: String, bookmark: Data? = nil, snapshotType: String? = nil, status: String) { self.name = name; self.bookmark = bookmark; self.snapshotType = snapshotType; self.status = status }
    public static func portable(_ data: Data, availableTypes: Set<String>? = nil) throws -> (data: Data, missing: Int) {
        var refs = try JSONDecoder().decode([FileReference].self, from: data)
        var missing = 0
        for index in refs.indices {
            refs[index].bookmark = nil
            refs[index].name = URL(fileURLWithPath: refs[index].name).lastPathComponent
            if let types = availableTypes, let type = refs[index].snapshotType, !types.contains(type) { refs[index].snapshotType = nil }
            if refs[index].snapshotType == nil { missing += 1; refs[index].status = "仅文件名；需重新选择原文件" }
        }
        let encoder = JSONEncoder(); encoder.outputFormatting = .sortedKeys
        return (try encoder.encode(refs), missing)
    }
}

