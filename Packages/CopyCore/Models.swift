public enum CopyError: Error, LocalizedError, Equatable {
    case database(String), invalid(String), budget, missingAsset(String), conflict, notFound, permission, unavailable(String)
    public var errorDescription: String? {
        switch self {
        case .database(let s): return "数据库错误：\(s)"
        case .invalid(let s): return "输入无效：\(s)"
        case .budget: return "存储预算不足；请导出或清理后重试。"
        case .missingAsset(let s): return "附件不可用：\(s)"
        case .conflict: return "内容已更新，请重新载入后编辑。"
        case .notFound: return "内容不存在或已删除。"
        case .permission: return "权限不足。"
        case .unavailable(let s): return s
        }
    }
}
public enum ContentRules {
    public static let excludedTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    public static func kind(types: Set<String>, text: String) -> ClipKind {
        if types.contains("public.file-url") || types.contains("com.copy.file-list") { return .files }
        if types.contains(where: { ["public.png", "public.tiff", "public.jpeg", "com.compuserve.gif", "public.heic"].contains($0) }) { return .image }
        if types.contains("public.rtf") || types.contains("public.html") { return .richText }
        let t = text.trimmingCharacters(in: .whitespacesAndNewlines)
        if t.range(of: "^#?[0-9A-Fa-f]{6}$", options: .regularExpression) != nil,
           t.hasPrefix("#") || t.range(of: "[a-fA-F]", options: .regularExpression) != nil { return .color }
        if let u = URL(string: t), ["http", "https"].contains(u.scheme?.lowercased() ?? ""), u.host != nil { return .url }
        return text.isEmpty ? .other : .text
    }
    public static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }
    public static func fingerprint(_ representations: [String: Data]) -> String {
        let rows = representations.keys.sorted().map { "\($0.utf8.count):\($0):\(digest(representations[$0]!))" }.joined(separator: "\n")
        return digest(Data(rows.utf8))
    }
    public static func validate(_ input: CaptureInput) throws {
        guard !input.representations.isEmpty else { throw CopyError.invalid("没有可保存的表示") }
        guard Set(input.representations.keys).isDisjoint(with: excludedTypes) else { throw CopyError.permission }
        guard input.text.utf8.count <= 5 * 1024 * 1024 else { throw CopyError.invalid("文本超过 5 MiB") }
        guard input.representations.values.allSatisfy({ $0.count <= 20 * 1024 * 1024 }), input.representations.values.reduce(0, { $0 + $1.count }) <= 50 * 1024 * 1024 else { throw CopyError.invalid("附件超过单项 20 MiB 或总计 50 MiB") }
    }
}

public struct QueueSession: Codable, Sendable {
    public enum State: String, Codable, Sendable { case paused, ready, preparing, dispatched, unknown, finished }
    public var ids: [UUID] = []
    public var cursor: Int = 0
    public var state: State = .paused
    public init() {}
    public var current: UUID? { ids.indices.contains(cursor) ? ids[cursor] : nil }
    public mutating func arm() { guard state != .unknown && state != .preparing && state != .dispatched else { return }; state = current == nil ? .finished : .ready }
    public mutating func begin() throws -> UUID { guard state == .ready, let id = current else { throw CopyError.invalid("队列未就绪") }; state = .preparing; return id }
    public mutating func sent() { guard state == .preparing else { return }; state = .dispatched; cursor += 1; state = current == nil ? .finished : .ready }
    public mutating func uncertain() { state = .unknown }
    public mutating func failBeforeDispatch() { state = .paused }
    public mutating func restore() { state = [.preparing, .dispatched, .unknown].contains(state) ? .unknown : .paused }
    public mutating func resolveUnknown(wasDelivered: Bool) { guard state == .unknown else { return }; if wasDelivered { cursor = min(cursor + 1, ids.count) }; state = .paused }
    public var canEdit: Bool { ![.unknown,.preparing,.dispatched].contains(state) }
    public mutating func back() { guard canEdit else { return }; cursor = max(0, cursor - 1); state = .paused }
    public mutating func append(_ values: [UUID]) throws { try ensureEditable(); ids += values; state = .paused }
    public mutating func reverseRemaining() throws { try ensureEditable(); ids.replaceSubrange(cursor..<ids.count,with:ids[cursor...].reversed()); state = .paused }
    public mutating func removePending(at index: Int) throws { try ensureEditable(); guard index >= cursor && ids.indices.contains(index) else { throw CopyError.invalid("只能删除未发送的队列项") }; ids.remove(at:index); state = .paused }
    public mutating func movePending(from: Int, to: Int) throws {
        try ensureEditable(); guard from >= cursor, to >= cursor, ids.indices.contains(from), ids.indices.contains(to) else { throw CopyError.invalid("只能调整未发送的队列项") }
        let value = ids.remove(at:from); ids.insert(value,at:to); state = .paused
    }
    private func ensureEditable() throws { guard canEdit else { throw CopyError.invalid("队列发送结果尚未确认，请先对账") }; guard cursor >= 0 && cursor <= ids.count else { throw CopyError.invalid("队列游标无效") } }
}
